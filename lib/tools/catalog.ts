export function filterTools(
  items: AITool[],
  filters: {
    search: string;
    category: string;
    pricing: string;
    letter: string;
    openSource: boolean;
    sort: string;
  },
) {
  return items
    .filter(
      (tool) =>
        matchesSearch(filters.search, [
          tool.name,
          tool.description,
          ...tool.categories,
          ...tool.useCases,
          ...tool.features,
        ]) &&
        (!filters.category || tool.categories.includes(filters.category)) &&
        (!filters.pricing || tool.pricing === filters.pricing) &&
        (!filters.letter || initialLetter(tool.name) === filters.letter) &&
        (!filters.openSource || tool.openSource),
    )
    .sort((a, b) =>
      filters.sort === 'za'
        ? b.name.localeCompare(a.name)
        : a.name.localeCompare(b.name),
    );
}
